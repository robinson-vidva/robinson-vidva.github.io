#!/usr/bin/env python3
"""Write one Yoast-style JSON-LD @graph per page from scripts/schema_data.json.

Usage: python3 scripts/build_schema.py [--check]

Page title, description, canonical and og:image are read from each HTML head.
Shared nodes: WebSite, Person, ImageObject. Per page: WebPage (or subtype),
BreadcrumbList, and Article or ItemList where schema_data.json defines one.
--check only reports pages whose block is out of date, exit 1 if any.
"""
import json
import re
import struct
import subprocess
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = json.loads((ROOT / "scripts" / "schema_data.json").read_text(encoding="utf-8"))
SITE = DATA["site"]["url"]
IDS = {"website": SITE + "/#website", "person": SITE + "/#person"}
BLOCK = re.compile(r'(?:[ \t]*<!--[^\n]*-->\n)?[ \t]*<script type="application/ld\+json">.*?</script>\n', re.S)
COMMENT = "  <!-- Structured data: generated by scripts/build_schema.py from scripts/schema_data.json -->\n"


def head_meta(html):
    def one(pat):
        m = re.search(pat, html, re.S)
        return m.group(1).strip() if m else None
    return {
        "title": one(r"<title>(.*?)</title>"),
        "description": one(r'name="description" content="([^"]*)"'),
        "canonical": one(r'rel="canonical" href="([^"]*)"'),
        "image": one(r'property="og:image" content="([^"]*)"'),
    }


def png_size(url):
    local = ROOT / url.replace(SITE + "/", "")
    if local.suffix.lower() == ".png" and local.exists():
        with local.open("rb") as fh:
            head = fh.read(24)
        if head[:8] == b"\x89PNG\r\n\x1a\n":
            return struct.unpack(">II", head[16:24])
    return None


def git_lastmod(rel):
    run = lambda *a: subprocess.run(["git", *a, "--", rel], cwd=ROOT, capture_output=True, text=True, check=True).stdout.strip()
    if run("status", "--porcelain"):
        return date.today().isoformat()
    return run("log", "-1", "--format=%ad", "--date=short") or None


def build_graph(rel, meta):
    page = DATA["pages"][rel]
    url = meta["canonical"]
    lang = DATA["site"]["language"]
    person = {"@type": "Person", "@id": IDS["person"], "url": SITE + "/",
              "image": {"@id": SITE + "/#personimage"}, **DATA["person"]}
    person_image = {"@type": "ImageObject", "@id": SITE + "/#personimage",
                    "url": SITE + "/images/Preview.png", "contentUrl": SITE + "/images/Preview.png"}
    size = png_size(person_image["url"])
    if size:
        person_image["width"], person_image["height"] = size
    website = {"@type": "WebSite", "@id": IDS["website"], "url": SITE + "/", "name": DATA["site"]["name"],
               "description": DATA["site"]["description"], "publisher": {"@id": IDS["person"]}, "inLanguage": lang}

    graph = [website, person, person_image]

    primary = None
    if meta["image"]:
        primary = {"@type": "ImageObject", "@id": url + "#primaryimage", "url": meta["image"], "contentUrl": meta["image"]}
        size = png_size(meta["image"])
        if size:
            primary["width"], primary["height"] = size
        graph.append(primary)

    crumbs = [{"@type": "ListItem", "position": 1, "name": "Home", "item": SITE + "/"}]
    names = page["breadcrumb"]
    for i, name in enumerate(names, start=2):
        item = {"@type": "ListItem", "position": i, "name": name}
        if i < len(names) + 1:
            item["item"] = SITE + "/" + ("articles.html" if name == "Articles" else "")
        else:
            item["item"] = url
        crumbs.append(item)
    breadcrumb = {"@type": "BreadcrumbList", "@id": url + "#breadcrumb", "itemListElement": crumbs}

    webpage = {"@type": page["type"], "@id": url, "url": url, "name": meta["title"],
               "isPartOf": {"@id": IDS["website"]}, "inLanguage": lang}
    if meta["description"]:
        webpage["description"] = meta["description"]
    if primary:
        webpage["primaryImageOfPage"] = {"@id": primary["@id"]}
        webpage["image"] = {"@id": primary["@id"]}
        webpage["thumbnailUrl"] = primary["url"]
    webpage["breadcrumb"] = {"@id": breadcrumb["@id"]}
    if page.get("about") == "person":
        webpage["about"] = {"@id": IDS["person"]}
    if page.get("mainEntity") == "person":
        webpage["mainEntity"] = {"@id": IDS["person"]}
    if "itemList" in page:
        webpage["author"] = {"@id": IDS["person"]}
        webpage["mainEntity"] = {"@type": "ItemList", "itemListElement": page["itemList"]}

    art = page.get("article")
    if art:
        webpage["datePublished"] = art.get("datePublished")
        webpage["dateModified"] = art.get("dateModified")
        node = {"@type": art["@type"], "@id": url + "#article", "isPartOf": {"@id": url},
                "mainEntityOfPage": {"@id": url}, "headline": art["headline"]}
        for k in ("alternativeHeadline", "datePublished", "dateModified"):
            if k in art:
                node[k] = art[k]
        if meta["description"]:
            node["description"] = meta["description"]
        node["author"] = {"@id": IDS["person"]}
        node["publisher"] = {"@id": IDS["person"]}
        if primary:
            node["image"] = {"@id": primary["@id"]}
            node["thumbnailUrl"] = primary["url"]
        node["inLanguage"] = lang
        for k in ("keywords", "about", "citation"):
            if k in art:
                node[k] = art[k]
        graph += [webpage, breadcrumb, node]
    else:
        lastmod = git_lastmod(rel)
        if lastmod:
            webpage["dateModified"] = lastmod
        graph += [webpage, breadcrumb]

    return {"@context": "https://schema.org", "@graph": graph}


def render(graph):
    body = json.dumps(graph, indent=2, ensure_ascii=False)
    body = "\n".join("  " + line for line in body.splitlines())
    return COMMENT + '  <script type="application/ld+json">\n' + body + "\n  </script>\n"


def main():
    check = "--check" in sys.argv
    stale = []
    for rel in DATA["pages"]:
        path = ROOT / rel
        html = path.read_text(encoding="utf-8")
        meta = head_meta(html)
        if not meta["canonical"]:
            sys.exit(f"{rel}: no canonical link")
        block = render(build_graph(rel, meta))
        found = list(BLOCK.finditer(html))
        if found:
            new = html[:found[0].start()] + block + BLOCK.sub("", html[found[0].end():])
        else:
            anchor = re.search(r"\n(?=\s*<link href=\"style.css)", html)
            new = html[:anchor.start() + 1] + "\n" + block + html[anchor.start() + 1:]
        if new != html:
            stale.append(rel)
            if not check:
                path.write_text(new, encoding="utf-8")
    if check:
        for rel in stale:
            print(f"out of date: {rel}")
        sys.exit(1 if stale else 0)
    print(f"updated {len(stale)} of {len(DATA['pages'])} pages")


if __name__ == "__main__":
    main()
